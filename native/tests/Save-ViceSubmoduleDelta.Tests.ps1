#Requires -Version 7.0
#Requires -Modules @{ ModuleName = 'Pester'; ModuleVersion = '5.7.0' }

# PLAN-NATIVERESTORE-001 step D0 (A01 DeltaComparison_ClassifiesEveryCurrentHunk, F08 inventory baseline):
# contract of native/Save-ViceSubmoduleDelta.ps1, proven on a mock git tree before the real run.
# BDPv4: Tag MockGate proves the manifest contract and every rejection; the real run is a separate receipt.

BeforeAll {
    $script:ScriptPath = (Resolve-Path -LiteralPath (Join-Path -Path (Join-Path -Path $PSScriptRoot -ChildPath '..') -ChildPath 'Save-ViceSubmoduleDelta.ps1')).Path

    function Initialize-MockSubmodule {
        param([string]$Root)
        New-Item -ItemType Directory -Path $Root -Force | Out-Null
        $git = { param([string[]]$a) & git -C $Root @a 2>&1 | Out-Null }
        & $git @('init', '-q', '-b', 'main')
        & $git @('config', 'user.email', 'test@example.invalid')
        & $git @('config', 'user.name', 'Mock')
        New-Item -ItemType Directory -Path (Join-Path $Root 'vice/src/drive') -Force | Out-Null
        Set-Content -LiteralPath (Join-Path $Root 'vice/src/mainc64cpu.c') -Value @('int a;', 'int b;', 'int c;', 'int d;', 'int e;', 'int f;', 'int g;', 'int h;') -Encoding ascii
        Set-Content -LiteralPath (Join-Path $Root 'vice/src/drive/drivecpu.c') -Value @('void reset(void) {', '    x = 1;', '}') -Encoding ascii
        Set-Content -LiteralPath (Join-Path $Root 'vice/src/untouched.c') -Value 'int z;' -Encoding ascii
        & $git @('add', '-A')
        & $git @('commit', '-q', '-m', 'pinned')
        # Tracked modifications (two files, three hunks).
        Set-Content -LiteralPath (Join-Path $Root 'vice/src/mainc64cpu.c') -Value @('#include "shim.h"', 'int a;', 'int b;', 'int c;', 'int d;', 'int e;', 'int f;', 'int g;', 'int h;', 'void hook(void) {}') -Encoding ascii
        Set-Content -LiteralPath (Join-Path $Root 'vice/src/drive/drivecpu.c') -Value @('void reset(void) {', '    x = 1;', '    cycle_accum = 0;', '}') -Encoding ascii
        # Untracked: generated by pattern, hidden path, injected by name.
        Set-Content -LiteralPath (Join-Path $Root 'vice/src/mainc64cpu.o') -Value 'obj' -Encoding ascii
        Set-Content -LiteralPath (Join-Path $Root 'vice/configure') -Value 'script' -Encoding ascii
        New-Item -ItemType Directory -Path (Join-Path $Root 'vice/src/.deps') -Force | Out-Null
        Set-Content -LiteralPath (Join-Path $Root 'vice/src/.deps/mainc64cpu.Po') -Value 'dep' -Encoding ascii
        Set-Content -LiteralPath (Join-Path $Root 'vice/.autoconf.out') -Value 'autoconf log' -Encoding ascii
        Set-Content -LiteralPath (Join-Path $Root 'vice/src/vice-shim-runtime.h') -Value '#define SHIM 1' -Encoding ascii
        return (& git -C $Root rev-parse HEAD).Trim()
    }

    function Export-ExpectedHunkTable {
        param([string]$Path, [string]$HostName, [object[]]$Rows)
        [ordered]@{ host = $HostName; rows = $Rows } | ConvertTo-Json -Depth 4 | Set-Content -LiteralPath $Path -Encoding utf8
    }

    $script:FullRows = @(
        [ordered]@{ file = 'vice/src/mainc64cpu.c'; oldStart = 1; row = 'H2' },
        [ordered]@{ file = 'vice/src/mainc64cpu.c'; oldStart = 6; row = 'H3' },
        [ordered]@{ file = 'vice/src/drive/drivecpu.c'; oldStart = 1; row = 'H6' }
    )
}

Describe 'Save-ViceSubmoduleDelta manifest contract' -Tag MockGate {
    BeforeEach {
        $script:Work = Join-Path ([IO.Path]::GetTempPath()) ('vsd-' + [Guid]::NewGuid().ToString('N'))
        $script:Sub = Join-Path $script:Work 'native/vice'
        $script:Receipt = Join-Path $script:Work 'receipt'
        $script:Head = Initialize-MockSubmodule -Root $script:Sub
        $script:Expected = Join-Path $script:Work 'expected-hunks.json'
        Export-ExpectedHunkTable -Path $script:Expected -HostName 'MOCKHOST' -Rows $script:FullRows
    }
    AfterEach {
        if (Test-Path -LiteralPath $script:Work) { Remove-Item -LiteralPath $script:Work -Recurse -Force }
    }

    It 'writes nothing under -WhatIf' {
        & $script:ScriptPath -SubmodulePath $script:Sub -ReceiptDirectory $script:Receipt -HostName 'MOCKHOST' -GitlinkSha $script:Head -ExpectedHunksPath $script:Expected -WhatIf | Out-Null
        Test-Path -LiteralPath $script:Receipt | Should -BeFalse
    }

    It 'records shas, counts, classified entries, hashes, preserved copies and the hunk map' {
        $result = & $script:ScriptPath -SubmodulePath $script:Sub -ReceiptDirectory $script:Receipt -HostName 'MOCKHOST' -GitlinkSha $script:Head -ExpectedHunksPath $script:Expected
        $result.Outcome | Should -Be 'Complete'
        $m = Get-Content -LiteralPath (Join-Path $script:Receipt 'manifest.json') -Raw | ConvertFrom-Json
        $m.schema | Should -Be 'phase-d-preservation/1'
        $m.host | Should -Be 'MOCKHOST'
        $m.gitlinkSha | Should -Be $script:Head
        $m.checkedOutSha | Should -Be $script:Head
        $m.cachedDiffEmpty | Should -BeTrue
        $m.counts.trackedModified | Should -Be 2
        $m.counts.untrackedTotal | Should -Be 5
        $m.counts.untrackedHidden | Should -Be 2
        $m.counts.untrackedOrdinary | Should -Be 3
        $m.counts.porcelainEntries | Should -Be 7
        ($m.entries | Where-Object path -eq 'vice/src/mainc64cpu.o').class | Should -Be 'generated'
        ($m.entries | Where-Object path -eq 'vice/.autoconf.out').class | Should -Be 'generated'
        ($m.entries | Where-Object path -eq 'vice/.autoconf.out').hidden | Should -BeTrue
        ($m.entries | Where-Object path -eq 'vice/configure').class | Should -Be 'generated'
        ($m.entries | Where-Object path -eq 'vice/src/.deps/mainc64cpu.Po').hidden | Should -BeTrue
        ($m.entries | Where-Object path -eq 'vice/src/vice-shim-runtime.h').class | Should -Be 'injected'
        ($m.entries | Where-Object path -eq 'vice/src/mainc64cpu.c').class | Should -Be 'modified'
        foreach ($e in $m.entries) {
            $e.sha256 | Should -Match '^[0-9A-F]{64}$'
            $e.length | Should -BeGreaterThan 0
        }
        $m.preserved.Count | Should -Be 3
        foreach ($p in $m.preserved) {
            (Get-FileHash -LiteralPath (Join-Path $script:Receipt $p.copyPath) -Algorithm SHA256).Hash | Should -Be $p.sha256
            (Get-FileHash -LiteralPath (Join-Path $script:Sub $p.path) -Algorithm SHA256).Hash | Should -Be $p.sha256
        }
        (Get-FileHash -LiteralPath (Join-Path $script:Receipt $m.patch.path) -Algorithm SHA256).Hash | Should -Be $m.patch.sha256
        $m.patch.hunks.Count | Should -Be 3
        $m.hunkMap.unclassified.Count | Should -Be 0
        $m.hunkMap.missingExpected.Count | Should -Be 0
        ($m.hunkMap.rows | Where-Object row -eq 'H6').file | Should -Be 'vice/src/drive/drivecpu.c'
        $m.hunkMap.rows.Count | Should -Be 3
    }

    It 'stops when the index is not clean' {
        Set-Content -LiteralPath (Join-Path $script:Sub 'vice/src/untouched.c') -Value 'int z; int y;' -Encoding ascii
        & git -C $script:Sub add vice/src/untouched.c 2>&1 | Out-Null
        { & $script:ScriptPath -SubmodulePath $script:Sub -ReceiptDirectory $script:Receipt -HostName 'MOCKHOST' -GitlinkSha $script:Head -ExpectedHunksPath $script:Expected } | Should -Throw '*staged*'
    }

    It 'stops when the gitlink does not match the checked-out commit' {
        { & $script:ScriptPath -SubmodulePath $script:Sub -ReceiptDirectory $script:Receipt -HostName 'MOCKHOST' -GitlinkSha ('0' * 40) -ExpectedHunksPath $script:Expected } | Should -Throw '*gitlink*'
    }

    It 'stops when the expected-hunk table is for another host' {
        Export-ExpectedHunkTable -Path $script:Expected -HostName 'OTHERHOST' -Rows $script:FullRows
        { & $script:ScriptPath -SubmodulePath $script:Sub -ReceiptDirectory $script:Receipt -HostName 'MOCKHOST' -GitlinkSha $script:Head -ExpectedHunksPath $script:Expected } | Should -Throw '*host*'
    }

    It 'reports a missing expected hunk as Blocked' {
        $rows = $script:FullRows + @([ordered]@{ file = 'vice/src/untouched.c'; oldStart = 1; row = 'H9' })
        Export-ExpectedHunkTable -Path $script:Expected -HostName 'MOCKHOST' -Rows $rows
        $result = & $script:ScriptPath -SubmodulePath $script:Sub -ReceiptDirectory $script:Receipt -HostName 'MOCKHOST' -GitlinkSha $script:Head -ExpectedHunksPath $script:Expected
        $result.Outcome | Should -Be 'Blocked'
        $m = Get-Content -LiteralPath (Join-Path $script:Receipt 'manifest.json') -Raw | ConvertFrom-Json
        $m.hunkMap.missingExpected.Count | Should -Be 1
        $m.hunkMap.missingExpected[0].file | Should -Be 'vice/src/untouched.c'
    }

    It 'reports a live hunk with no row as unclassified and Blocked, and a same-file context shift as an explained difference' {
        $rows = @(
            [ordered]@{ file = 'vice/src/mainc64cpu.c'; oldStart = 1; row = 'H2' },
            [ordered]@{ file = 'vice/src/mainc64cpu.c'; oldStart = 7; row = 'H3' }
        )
        Export-ExpectedHunkTable -Path $script:Expected -HostName 'MOCKHOST' -Rows $rows
        $result = & $script:ScriptPath -SubmodulePath $script:Sub -ReceiptDirectory $script:Receipt -HostName 'MOCKHOST' -GitlinkSha $script:Head -ExpectedHunksPath $script:Expected
        $result.Outcome | Should -Be 'Blocked'
        $m = Get-Content -LiteralPath (Join-Path $script:Receipt 'manifest.json') -Raw | ConvertFrom-Json
        ($m.hunkMap.unclassified | Where-Object file -eq 'vice/src/drive/drivecpu.c').Count | Should -Be 1
        ($m.hunkMap.explainedDifferences | Where-Object { $_.file -eq 'vice/src/mainc64cpu.c' -and $_.row -eq 'H3' }).Count | Should -Be 1
    }

    It 'reports an untracked path that matches no pattern and no injected name as unclassified and Blocked' {
        Set-Content -LiteralPath (Join-Path $script:Sub 'vice/src/mystery.c') -Value 'int q;' -Encoding ascii
        $result = & $script:ScriptPath -SubmodulePath $script:Sub -ReceiptDirectory $script:Receipt -HostName 'MOCKHOST' -GitlinkSha $script:Head -ExpectedHunksPath $script:Expected
        $result.Outcome | Should -Be 'Blocked'
        $m = Get-Content -LiteralPath (Join-Path $script:Receipt 'manifest.json') -Raw | ConvertFrom-Json
        ($m.entries | Where-Object path -eq 'vice/src/mystery.c').class | Should -Be 'unclassified'
    }

    It 'records native libraries found under the search roots with hashes, and none when absent' {
        $lib = Join-Path $script:Work 'native/vice_x64.so'
        Set-Content -LiteralPath $lib -Value 'fake' -Encoding ascii
        & $script:ScriptPath -SubmodulePath $script:Sub -ReceiptDirectory $script:Receipt -HostName 'MOCKHOST' -GitlinkSha $script:Head -ExpectedHunksPath $script:Expected -LibrarySearchRoots @((Join-Path $script:Work 'native'))
        $m = Get-Content -LiteralPath (Join-Path $script:Receipt 'manifest.json') -Raw | ConvertFrom-Json
        $m.libraries.Count | Should -Be 1
        $m.libraries[0].sha256 | Should -Be (Get-FileHash -LiteralPath $lib -Algorithm SHA256).Hash
        Remove-Item -LiteralPath $lib -Force
        Remove-Item -LiteralPath $script:Receipt -Recurse -Force
        & $script:ScriptPath -SubmodulePath $script:Sub -ReceiptDirectory $script:Receipt -HostName 'MOCKHOST' -GitlinkSha $script:Head -ExpectedHunksPath $script:Expected -LibrarySearchRoots @((Join-Path $script:Work 'native')) | Out-Null
        $m2 = Get-Content -LiteralPath (Join-Path $script:Receipt 'manifest.json') -Raw | ConvertFrom-Json
        @($m2.libraries).Count | Should -Be 0
    }
}
