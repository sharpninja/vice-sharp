#Requires -Version 7.0
<#
.SYNOPSIS
PLAN-NATIVERESTORE-001 step D0: measure and preserve the native/vice submodule delta, read only except for the receipt.

.DESCRIPTION
Records the gitlink and checked-out commit, the full tracked diff (patch file with SHA256 and a hunk list), the
porcelain status with explicit counts (tracked modified, untracked ordinary, untracked hidden), a per-path
classification (modified, generated by pattern, injected by name, or unclassified), SHA256 and length of every
listed path (the F08 inventory baseline), copies of every modified tracked file and every injected source file
under the receipt with hashes (never moved), any native library found under the search roots, and the A01 hunk map
against the expected-hunk table for this host (rows, explained same-file differences, unclassified live hunks,
missing expected hunks). Stops before writing on a staged change, a gitlink mismatch, or a table for another host.
Outcome is Complete when every hunk and every untracked path is classified, otherwise Blocked (the receipt is still
written so the blocker is observable). Nothing under the submodule is modified, checked out, cleaned or built.

.PARAMETER SubmodulePath
Path of the native/vice checkout.

.PARAMETER ReceiptDirectory
Directory to create for the receipt (manifest.json, the patch, preserved copies).

.PARAMETER HostName
Name of the host producing the receipt; must equal the expected-hunk table's host.

.PARAMETER GitlinkSha
The superproject's recorded gitlink for the submodule; must equal the checked-out commit.

.PARAMETER ExpectedHunksPath
JSON file: { host, rows: [ { file, oldStart, row } ] } listing the hunks the classification expects on this host.

.PARAMETER LibrarySearchRoots
Directories searched (non-recursively) for vice_x64, vice-shim and vice_xvic libraries.
#>
[CmdletBinding(SupportsShouldProcess)]
param(
    [Parameter(Mandatory)][string] $SubmodulePath,
    [Parameter(Mandatory)][string] $ReceiptDirectory,
    [Parameter(Mandatory)][string] $HostName,
    [Parameter(Mandatory)][string] $GitlinkSha,
    [Parameter(Mandatory)][string] $ExpectedHunksPath,
    [string[]] $LibrarySearchRoots = @()
)
Set-StrictMode -Version Latest
$ErrorActionPreference = 'Stop'

function Invoke-Git {
    param([string[]] $Arguments)
    $output = & git -C $SubmodulePath @Arguments 2>&1
    if ($LASTEXITCODE -ne 0) { throw "git $($Arguments -join ' ') failed with exit $LASTEXITCODE`: $output" }
    return @($output | ForEach-Object { [string]$_ })
}

$generatedPatterns = @(
    '\.o$', '\.a$', '\.la$', '\.lo$', '\.exe$', '\.dll$', '\.so$', '\.Po$', '\.Plo$', '\.Tpo$',
    '(^|/)Makefile$', '\.in$', '(^|/)configure$', '(^|/)config\.(status|log|cache|h|guess|sub)$',
    '(^|/)(compile|depcomp|missing|ylwrap|install-sh|ltmain\.sh|libtool|aclocal\.m4|stamp-h1|test-driver)$',
    '(^|/)(COPYING|INSTALL)$', '(^|/)autom4te\.cache(/|$)', '\.po$', '\.gmo$', '\.mo$', '(^|/)mon_lex\.c$', '(^|/)mon_parse\.[ch]$',
    '(^|/)psiddrv\.h$', '\.pyc$', '(^|/)\.deps(/|$)', '(^|/)\.libs(/|$)', '(^|/)\.dirstamp$',
    '(^|/)\.(aclocal|autoconf|autoheader|automake|libtoolize)\.out$'
)
$injectedNames = @('vice/src/vice-shim-runtime.h', '.vice-shim-configure-flags')

$table = Get-Content -LiteralPath $ExpectedHunksPath -Raw | ConvertFrom-Json
if ([string]$table.host -cne $HostName) { throw "Expected-hunk table is for host '$($table.host)', not '$HostName'." }

$checkedOut = ((Invoke-Git @('rev-parse', 'HEAD')) -join '').Trim()
if ($checkedOut -cne $GitlinkSha) { throw "Recorded gitlink $GitlinkSha does not equal the checked-out commit $checkedOut." }

& git -C $SubmodulePath diff --cached --quiet 2>&1 | Out-Null
if ($LASTEXITCODE -ne 0) { throw 'The submodule index has staged changes; D0 requires an empty staged diff.' }

$porcelain = @(Invoke-Git @('status', '--porcelain=v1', '-uall', '--untracked-files=all')) | Where-Object { $_ -ne '' }
# Explicit prefixes: a user-level diff.mnemonicPrefix or diff.noprefix setting would otherwise change the file lines.
$patchLines = @(& git -C $SubmodulePath diff --no-color --src-prefix=a/ --dst-prefix=b/ 2>&1 | ForEach-Object { [string]$_ })
$patchText = ($patchLines -join "`n")
if ($patchLines.Count -gt 0) { $patchText += "`n" }

# Hunk list from the patch: file from "diff --git a/X b/X", header from "@@ -a,b +c,d @@".
$hunks = [System.Collections.Generic.List[object]]::new()
$currentFile = $null
$index = 0
foreach ($line in $patchLines) {
    if ($line -match '^diff --git a/(.+?) b/(.+)$') { $currentFile = $Matches[2]; continue }
    if ($line -match '^@@ -(\d+)(?:,(\d+))? \+(\d+)(?:,(\d+))? @@') {
        $index++
        $hunks.Add([ordered]@{ index = $index; file = $currentFile; header = $line; oldStart = [int]$Matches[1] })
    }
}

# Entries from porcelain.
$entries = [System.Collections.Generic.List[object]]::new()
$trackedModified = 0; $untrackedOrdinary = 0; $untrackedHidden = 0
foreach ($row in $porcelain) {
    $code = $row.Substring(0, 2)
    $path = $row.Substring(3)
    if ($path.StartsWith('"') -and $path.EndsWith('"')) { $path = $path.Substring(1, $path.Length - 2) }
    $full = Join-Path $SubmodulePath $path
    $hidden = ($path -split '/') | Where-Object { $_.StartsWith('.') } | Select-Object -First 1
    $isHidden = [bool]$hidden
    $sha = $null; $length = 0
    if (Test-Path -LiteralPath $full -PathType Leaf) {
        $sha = (Get-FileHash -LiteralPath $full -Algorithm SHA256).Hash
        $length = (Get-Item -LiteralPath $full -Force).Length
    }
    if ($code -eq '??') {
        $class = 'unclassified'
        if ($injectedNames -contains $path) { $class = 'injected' }
        elseif ($generatedPatterns | Where-Object { $path -match $_ } | Select-Object -First 1) { $class = 'generated' }
        if ($isHidden) { $untrackedHidden++ } else { $untrackedOrdinary++ }
    } elseif ($code.Trim() -eq 'M') {
        $class = 'modified'
        $trackedModified++
    } else {
        $class = 'unclassified'
    }
    $entries.Add([ordered]@{ path = $path; status = $code.Trim(); class = $class; hidden = $isHidden; sha256 = $sha; length = $length })
}

# Hunk map against the expected table.
$rows = [System.Collections.Generic.List[object]]::new()
$explained = [System.Collections.Generic.List[object]]::new()
$unclassified = [System.Collections.Generic.List[object]]::new()
$missing = [System.Collections.Generic.List[object]]::new()
$expectedRows = @($table.rows)
$matched = [System.Collections.Generic.HashSet[int]]::new()
foreach ($h in $hunks) {
    $exact = $expectedRows | Where-Object { $_.file -eq $h.file -and [int]$_.oldStart -eq $h.oldStart } | Select-Object -First 1
    if ($exact) {
        $rows.Add([ordered]@{ index = $h.index; file = $h.file; header = $h.header; row = $exact.row })
        [void]$matched.Add([Array]::IndexOf($expectedRows, $exact))
        continue
    }
    $sameFile = $expectedRows | Where-Object { $_.file -eq $h.file -and -not $matched.Contains([Array]::IndexOf($expectedRows, $_)) } | Sort-Object { [Math]::Abs([int]$_.oldStart - $h.oldStart) } | Select-Object -First 1
    if ($sameFile) {
        $rows.Add([ordered]@{ index = $h.index; file = $h.file; header = $h.header; row = $sameFile.row })
        $explained.Add([ordered]@{ index = $h.index; file = $h.file; header = $h.header; row = $sameFile.row; expectedOldStart = [int]$sameFile.oldStart; liveOldStart = $h.oldStart; kind = 'same file, different context' })
        [void]$matched.Add([Array]::IndexOf($expectedRows, $sameFile))
        continue
    }
    $unclassified.Add([ordered]@{ index = $h.index; file = $h.file; header = $h.header })
}
for ($i = 0; $i -lt $expectedRows.Count; $i++) {
    if (-not $matched.Contains($i)) { $missing.Add([ordered]@{ file = $expectedRows[$i].file; oldStart = [int]$expectedRows[$i].oldStart; row = $expectedRows[$i].row }) }
}

# Libraries.
$libraries = [System.Collections.Generic.List[object]]::new()
foreach ($root in $LibrarySearchRoots) {
    if (-not (Test-Path -LiteralPath $root)) { continue }
    foreach ($f in Get-ChildItem -LiteralPath $root -File -Force) {
        if ($f.Name -match '^(lib)?(vice_x64|vice-shim|vice_xvic)(\.dll|\.so|\.dylib)?$') {
            $libraries.Add([ordered]@{ name = $f.Name; path = $f.FullName; sha256 = (Get-FileHash -LiteralPath $f.FullName -Algorithm SHA256).Hash; length = $f.Length })
        }
    }
}

$unclassifiedEntries = @($entries | Where-Object { $_.class -eq 'unclassified' })
$outcome = if ($unclassified.Count -eq 0 -and $missing.Count -eq 0 -and $unclassifiedEntries.Count -eq 0) { 'Complete' } else { 'Blocked' }

$preserved = [System.Collections.Generic.List[object]]::new()
$patchName = 'native-vice-tracked.patch'
$manifest = [ordered]@{
    schema = 'phase-d-preservation/1'
    host = $HostName
    timestampLocal = (Get-Date -Format 'yyyy-MM-ddTHH:mm:ss')
    submodulePath = (Resolve-Path -LiteralPath $SubmodulePath).Path
    gitlinkSha = $GitlinkSha
    checkedOutSha = $checkedOut
    cachedDiffEmpty = $true
    patch = [ordered]@{ path = $patchName; sha256 = $null; bytes = 0; hunks = @($hunks) }
    counts = [ordered]@{
        porcelainEntries = $porcelain.Count
        trackedModified = $trackedModified
        untrackedOrdinary = $untrackedOrdinary
        untrackedHidden = $untrackedHidden
        untrackedTotal = $untrackedOrdinary + $untrackedHidden
    }
    entries = @($entries)
    preserved = @()
    libraries = @($libraries)
    hunkMap = [ordered]@{
        expectedHost = [string]$table.host
        expectedRows = $expectedRows.Count
        rows = @($rows)
        explainedDifferences = @($explained)
        unclassified = @($unclassified)
        missingExpected = @($missing)
    }
    outcome = $outcome
}

if ($PSCmdlet.ShouldProcess($ReceiptDirectory, "write the D0 preservation receipt ($outcome)")) {
    New-Item -ItemType Directory -Path $ReceiptDirectory -Force | Out-Null
    $patchPath = Join-Path $ReceiptDirectory $patchName
    [IO.File]::WriteAllText($patchPath, $patchText, [Text.UTF8Encoding]::new($false))
    $manifest.patch.sha256 = (Get-FileHash -LiteralPath $patchPath -Algorithm SHA256).Hash
    $manifest.patch.bytes = (Get-Item -LiteralPath $patchPath).Length
    foreach ($e in $entries) {
        if ($e.class -in @('modified', 'injected') -and $e.sha256) {
            $copyRel = Join-Path 'preserved' $e.path
            $copyFull = Join-Path $ReceiptDirectory $copyRel
            New-Item -ItemType Directory -Path (Split-Path -Parent $copyFull) -Force | Out-Null
            Copy-Item -LiteralPath (Join-Path $SubmodulePath $e.path) -Destination $copyFull
            $copyHash = (Get-FileHash -LiteralPath $copyFull -Algorithm SHA256).Hash
            if ($copyHash -cne $e.sha256) { throw "Preserved copy hash mismatch for $($e.path)." }
            $preserved.Add([ordered]@{ path = $e.path; copyPath = $copyRel; sha256 = $copyHash; length = $e.length })
        }
    }
    $manifest.preserved = @($preserved)
    $manifest | ConvertTo-Json -Depth 6 | Set-Content -LiteralPath (Join-Path $ReceiptDirectory 'manifest.json') -Encoding utf8
}

[pscustomobject]@{
    Outcome = $outcome
    Receipt = $ReceiptDirectory
    TrackedModified = $trackedModified
    UntrackedTotal = $untrackedOrdinary + $untrackedHidden
    Hunks = $hunks.Count
    Unclassified = $unclassified.Count + $unclassifiedEntries.Count
    MissingExpected = $missing.Count
}
